// WCAG 2.1 contrast check for both themes. Writes docs/contrast-report.md.
// Run: npm run contrast
const fs = require('fs');
const hex = h => { h = h.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); };
const mix = (fg, a, bg) => fg.map((c, i) => Math.round(c * a + bg[i] * (1 - a))); // alpha over solid
const lum = rgb => { const [r, g, b] = rgb.map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };
const toHex = c => '#' + c.map(v => v.toString(16).padStart(2, '0')).join('').toUpperCase();

const themes = {
  Blackboard: { board: '#1E2B25', frame: '#6B4A2E', ink: '#F3F0E8', a1: '#F6E27F', a2: '#F4A6B8', a3: '#9FD3F0', a4: '#B5E3A1', smudgeA: 0.08, smudgeC: '#F3F0E8', softA: 0.78, onA1: '#1E2B25', onFrame: '#F3F0E8', paper: '#FBF6E4', linkCard: '#9FD3F0' },
  Whiteboard: { board: '#FAFAF7', frame: '#B8BCC2', ink: '#1F2937', a1: '#1D4ED8', a2: '#C62828', a3: '#2E7D32', a4: '#EA580C', smudgeA: 0.06, smudgeC: '#1F2937', softA: 0.82, onA1: '#FAFAF7', onFrame: '#1F2937', paper: '#FFFDF5', linkCard: '#2A7230' },
};

let md = '# Contrast report\n\nGenerated by `tools/contrast.js` (WCAG 2.1 relative-luminance formula). Translucent tokens are composited onto the board before measuring.\nAA needs 4.5:1 for normal text, 3:1 for large text (24 px, or 18.66 px bold) and for non-text UI such as icons, outlines and focus rings.\n\n';
let fails = 0;
for (const [name, t] of Object.entries(themes)) {
  const board = hex(t.board), smudge = mix(hex(t.smudgeC), t.smudgeA, board), soft = mix(hex(t.ink), t.softA, board);
  const paper = hex(t.paper);
  const reelBg = mix([20, 28, 24], 0.78, [255, 255, 255]); // handle tag over a white video frame (worst case)
  const rows = [
    ['--ink on --board', 'Body text', hex(t.ink), board, 4.5],
    ['--ink on --smudge card', 'Card body text', hex(t.ink), smudge, 4.5],
    ['--ink-soft on --board', 'Captions, meta text', soft, board, 4.5],
    ['--accent-1 on --board', 'Headings (large)', hex(t.a1), board, 3],
    ['--accent-1 on --board', 'Accent-1 as small text', hex(t.a1), board, 4.5],
    ['--accent-2 on --board', 'Eyebrows, "New" tags', hex(t.a2), board, 4.5],
    ['--accent-3 on --board', 'Links, secondary CTA', hex(t.a3), board, 4.5],
    ['--link-on-smudge on --smudge card', 'Links inside cards', hex(t.linkCard), smudge, 4.5],
    ['--accent-4 on --board', 'Icons, doodles (non-text)', hex(t.a4), board, 3],
    ['--accent-1 on --board', 'Focus ring (non-text)', hex(t.a1), board, 3],
    ['button text on --accent-1', 'Primary CTA label', hex(t.onA1), hex(t.a1), 4.5],
    ['--on-frame on --frame', 'Top strip, footer edge', hex(t.onFrame), hex(t.frame), 4.5],
    ['paper ink #24292F on paper', 'Notice title', hex('#24292F'), paper, 4.5],
    ['#3B4250 on paper', 'Notice summary', hex('#3B4250'), paper, 4.5],
    ['#4B5563 on paper', 'Notice date and meta', hex('#4B5563'), paper, 4.5],
    ['#B3261E on paper', '"New" on notes', hex('#B3261E'), paper, 4.5],
    ['#1D4ED8 on paper', 'CBSE stamp', hex('#1D4ED8'), paper, 4.5],
    ['#F3F0E8 on reel tag', 'Handle tag over white video', hex('#F3F0E8'), reelBg, 4.5],
  ];
  md += `## ${name}\n\n| Pair | Use | Foreground | Background | Ratio | Needs | Result |\n|---|---|---|---|---|---|---|\n`;
  for (const [pair, use, fg, bg, need] of rows) {
    const r = ratio(fg, bg); const ok = r >= need; if (!ok) fails++;
    md += `| ${pair} | ${use} | ${toHex(fg)} | ${toHex(bg)} | ${r.toFixed(2)}:1 | ${need}:1 | ${ok ? 'Pass' : '**FAIL**'} |\n`;
  }
  md += '\n';
}
md += `Note: in Whiteboard, --accent-4 (marker orange) is for icons and doodles only. It is not used for text.\n\nFailures: ${fails}\n`;
fs.writeFileSync('docs/contrast-report.md', md);
console.log(md);
process.exitCode = fails ? 1 : 0;
